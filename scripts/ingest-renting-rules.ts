// Builds app/lib/data/renting-rules.json from the curated pages in
// knowledge/renting/. Run it by hand after editing a page:
//
//   npm run ingest:renting            chunk, embed and write the JSON
//   npm run ingest:renting -- --check chunk only, print a report, no API call
//
// Steps (an ETL pipeline: extract, transform, load):
//   1. read every knowledge/renting/*.md page
//   2. split each page into chunks by "##" heading
//   3. turn every chunk into a vector with one batched OpenAI call
//   4. write chunks, vectors and page dates to the JSON file
//
// It runs with plain Node (type stripping), so it only imports Node built-ins
// and the import-free chunker.

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  chunkRentingRulePage,
  embeddingInput,
  parseRentingRulePage,
} from "../app/lib/rentingRuleChunks.ts";
import type { RentingRulePage } from "../app/lib/rentingRuleChunks.ts";

const knowledgeDir = "knowledge/renting";
const outputFile = "app/lib/data/renting-rules.json";
// Must match what app/lib/services/rentingRules.ts embeds questions with:
// vectors from different models or sizes cannot be compared.
const embeddingModel = "text-embedding-3-small";
const embeddingDimensions = 512;

type PreviousFile = { pages?: { slug: string; textHash: string }[] };

function readPages() {
  return readdirSync(knowledgeDir)
    .filter((file) => file.endsWith(".md") && file !== "README.md")
    .sort()
    .map((file) =>
      parseRentingRulePage(
        file.replace(/\.md$/, ""),
        readFileSync(join(knowledgeDir, file), "utf8"),
      ),
    );
}

function hashText(page: RentingRulePage) {
  return createHash("sha256").update(page.body).digest("hex").slice(0, 16);
}

// Prints which pages are new, changed or removed since the last ingest, so a
// refresh can be reviewed page by page.
function reportChanges(pages: RentingRulePage[]) {
  const previous: PreviousFile = existsSync(outputFile)
    ? JSON.parse(readFileSync(outputFile, "utf8"))
    : {};
  const oldHashes = new Map(
    (previous.pages ?? []).map((page) => [page.slug, page.textHash]),
  );

  for (const page of pages) {
    const oldHash = oldHashes.get(page.slug);
    const status =
      oldHash === undefined
        ? "new"
        : oldHash === hashText(page)
          ? "unchanged"
          : "changed";
    console.log(`  ${status.padEnd(9)} ${page.slug}`);
    oldHashes.delete(page.slug);
  }

  for (const slug of oldHashes.keys()) {
    console.log(`  removed   ${slug}`);
  }
}

async function embed(inputs: string[]) {
  const apiKey = process.env.OPENAI_API_KEY?.trim();

  if (!apiKey) {
    throw new Error("OPENAI_API_KEY is not set (add it to .env.local).");
  }

  const response = await fetch("https://api.openai.com/v1/embeddings", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: embeddingModel,
      dimensions: embeddingDimensions,
      input: inputs,
    }),
  });

  if (!response.ok) {
    throw new Error(
      `OpenAI embeddings failed: ${response.status} ${await response.text()}`,
    );
  }

  const body = (await response.json()) as {
    data: { index: number; embedding: number[] }[];
    usage?: { total_tokens: number };
  };
  console.log(
    `Embedded ${inputs.length} chunks, ${body.usage?.total_tokens ?? "?"} tokens.`,
  );

  return body.data
    .sort((a, b) => a.index - b.index)
    .map(({ embedding }) =>
      // Five decimals keep the file small without changing the ranking.
      embedding.map((value) => Math.round(value * 1e5) / 1e5),
    );
}

async function main() {
  for (const file of [".env.development.local", ".env.local", ".env"]) {
    if (existsSync(file)) {
      process.loadEnvFile(file);
    }
  }

  const pages = readPages();
  const chunks = pages.flatMap(chunkRentingRulePage);

  console.log(`${pages.length} pages, ${chunks.length} chunks.`);
  reportChanges(pages);

  if (process.argv.includes("--check")) {
    return;
  }

  const vectors = await embed(chunks.map(embeddingInput));
  const dataAsOf = pages
    .map((page) => page.retrievedAt)
    .sort()
    .at(-1);

  const file = {
    source: "Consumer Affairs Victoria renting guidance",
    attribution: "© State of Victoria (Consumer Affairs Victoria)",
    licence: "CC BY 4.0, https://creativecommons.org/licenses/by/4.0/",
    note: "Generated by scripts/ingest-renting-rules.ts from knowledge/renting/. Do not edit by hand.",
    embeddingModel,
    embeddingDimensions,
    dataAsOf,
    pages: pages.map((page) => ({
      slug: page.slug,
      title: page.title,
      url: page.url,
      pageUpdated: page.pageUpdated,
      retrievedAt: page.retrievedAt,
      textHash: hashText(page),
    })),
    chunks: chunks.map((chunk, index) => ({
      ...chunk,
      embedding: vectors[index],
    })),
  };

  writeFileSync(outputFile, `${JSON.stringify(file)}\n`);
  console.log(`Wrote ${outputFile}.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
